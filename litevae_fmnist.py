# ----------------------------------------------------------------------
# 2D Haar discrete wavelet transform (DWT) and its inverse (IDWT)
# Implemented directly with tensor slicing (orthonormal Haar basis).
# ----------------------------------------------------------------------
def haar_dwt2d(x):
    """Forward 2-level-agnostic single-scale 2D Haar DWT.
    x: [B, C, H, W] with even H, W -> returns 4 subbands [B, C, H/2, W/2]."""
    x00 = x[:, :, 0::2, 0::2]
    x01 = x[:, :, 0::2, 1::2]
    x10 = x[:, :, 1::2, 0::2]
    x11 = x[:, :, 1::2, 1::2]
    ll = (x00 + x01 + x10 + x11) / 2.0
    lh = (x00 - x01 + x10 - x11) / 2.0   # horizontal detail
    hl = (x00 + x01 - x10 - x11) / 2.0   # vertical detail
    hh = (x00 - x01 - x10 + x11) / 2.0   # diagonal detail
    return ll, lh, hl, hh


def haar_idwt2d(ll, lh, hl, hh):
    """Inverse single-scale 2D Haar DWT."""
    x00 = (ll + lh + hl + hh) / 2.0
    x01 = (ll - lh + hl - hh) / 2.0
    x10 = (ll + lh - hl - hh) / 2.0
    x11 = (ll - lh - hl + hh) / 2.0
    b, c, h, w = x00.shape
    out = x00.new_empty(b, c, h * 2, w * 2)
    out[:, :, 0::2, 0::2] = x00
    out[:, :, 0::2, 1::2] = x01
    out[:, :, 1::2, 0::2] = x10
    out[:, :, 1::2, 1::2] = x11
    return out


# ----------------------------------------------------------------------
# Encoder: DWT front-end -> per-band feature extraction -> aggregation
# ----------------------------------------------------------------------
class DWTEncoder(nn.Module):
    """VAE encoder that first decomposes the image with DWT.

    For 28x28 input with num_levels=2:
      level1 bands: 14x14 (lh1, hl1, hh1 -> 3 channels)
      level2 bands: 7x7   (ll2, lh2, hl2, hh2 -> 4 channels)
    """
    def __init__(self, in_channels=1, latent_dim=16, num_levels=2,
                 base_ch=32):
        super().__init__()
        self.num_levels = num_levels
        self.latent_dim = latent_dim

        # Feature extraction at finest band resolution (14x14)
        self.feat1 = nn.Sequential(
            nn.Conv2d(3 * in_channels, base_ch, 3, padding=1),
            nn.BatchNorm2d(base_ch), nn.GELU(),
            nn.Conv2d(base_ch, base_ch, 3, padding=1),
            nn.BatchNorm2d(base_ch), nn.GELU(),
        )
        # Feature extraction at coarsest band resolution (7x7)
        self.feat2 = nn.Sequential(
            nn.Conv2d(4 * in_channels, base_ch, 3, padding=1),
            nn.BatchNorm2d(base_ch), nn.GELU(),
            nn.Conv2d(base_ch, base_ch, 3, padding=1),
            nn.BatchNorm2d(base_ch), nn.GELU(),
        )
        # Aggregation
        self.agg = nn.Sequential(
            nn.Conv2d(2 * base_ch, base_ch, 3, padding=1), nn.GELU(),
            nn.Conv2d(base_ch, base_ch, 1), nn.GELU(),
        )
        self.to_latent = nn.Conv2d(base_ch, 2 * latent_dim, 1)  # mu + logvar

    def forward(self, x):
        # DWT front end
        ll1, lh1, hl1, hh1 = haar_dwt2d(x)              # 14x14
        ll2, lh2, hl2, hh2 = haar_dwt2d(ll1)            # 7x7

        # concatenate level-1 high-frequency bands
        b1 = torch.cat([lh1, hl1, hh1], dim=1)          # [B,3C,14,14]
        f1 = self.feat1(b1)                             # [B,base,14,14]
        f1 = F.avg_pool2d(f1, 2)                        # [B,base,7,7]

        # concatenate level-2 bands (low + high)
        b2 = torch.cat([ll2, lh2, hl2, hh2], dim=1)     # [B,4C,7,7]
        f2 = self.feat2(b2)                             # [B,base,7,7]

        agg = torch.cat([f1, f2], dim=1)                # [B,2base,7,7]
        h = self.agg(agg)                               # [B,base,7,7]
        params = self.to_latent(h)                      # [B,2*latent,7,7]
        mu, logvar = params[:, :self.latent_dim], params[:, self.latent_dim:]
        return mu, logvar


# ----------------------------------------------------------------------
# Decoder: purely convolutional transposed network
# ----------------------------------------------------------------------
class ConvDecoder(nn.Module):
    def __init__(self, latent_dim=16, base_ch=32):
        super().__init__()
        self.net = nn.Sequential(
            nn.ConvTranspose2d(latent_dim, base_ch * 2, 4, stride=2, padding=1),  # 7->14
            nn.BatchNorm2d(base_ch * 2), nn.GELU(),
            nn.ConvTranspose2d(base_ch * 2, base_ch, 4, stride=2, padding=1),     # 14->28
            nn.BatchNorm2d(base_ch), nn.GELU(),
            nn.Conv2d(base_ch, 1, 3, padding=1),
            nn.Sigmoid(),
        )

    def forward(self, z):
        # z: [B, latent_dim, 7, 7] spatial latent grid -> upsample to 28x28
        return self.net(z)


# ----------------------------------------------------------------------
# Full LiteVAE (VAE) module
# ----------------------------------------------------------------------
class LiteVAE(nn.Module):
    def __init__(self, in_channels=1, latent_dim=16):
        super().__init__()
        self.encoder = DWTEncoder(in_channels, latent_dim)
        self.decoder = ConvDecoder(latent_dim)
        self.latent_dim = latent_dim

    def reparameterize(self, mu, logvar):
        std = torch.exp(0.5 * logvar)
        eps = torch.randn_like(std)
        return mu + eps * std

    def forward(self, x):
        mu, logvar = self.encoder(x)
        z = self.reparameterize(mu, logvar)  # [B, latent_dim, 7, 7]
        recon = self.decoder(z)
        return recon, mu, logvar


# ----------------------------------------------------------------------
# Losses: reconstruction (MSE) + KL divergence
# ----------------------------------------------------------------------
def vae_loss(recon, target, mu, logvar):
    recon_loss = F.mse_loss(recon, target, reduction="mean")
    kl = -0.5 * torch.sum(1 + logvar - mu.pow(2) - logvar.exp()) / mu.shape[0]
    return recon_loss, kl


def kl_weight(epoch, max_epochs, warmup_frac=0.2, max_beta=1.0):
    """Linear anneal of KL weight to avoid posterior collapse early on.
    Kept for API compatibility; the KL scale in main() is set small by default
    (as in stable-diffusion / LiteVAE training where reconstruction dominates)."""
    warmup = max(1, int(max_epochs * warmup_frac))
    if epoch < warmup:
        return max_beta * (epoch + 1) / warmup
    return max_beta


# ----------------------------------------------------------------------
# Metrics
# ----------------------------------------------------------------------
def psnr(a, b, max_val=1.0):
    mse = torch.mean((a - b) ** 2).item()
    if mse == 0:
        return float("inf")
    return 10.0 * np.log10(max_val ** 2 / mse)


def _gaussian_kernel(ksize=11, sigma=1.5):
    ax = torch.linspace(-(ksize - 1) / 2, (ksize - 1) / 2, ksize)
    g = torch.exp(-(ax ** 2) / (2 * sigma ** 2))
    g = (g / g.sum()).view(1, 1, -1, 1)
    return g, g.transpose(2, 3)


def ssim(a, b, ksize=11, sigma=1.5):
    """Structural similarity (full-image, single channel)."""
    a = a.float()
    b = b.float()
    gx, gy = _gaussian_kernel(ksize, sigma)
    # img: [B,1,H,W]
    mu_a = F.conv2d(a.view(-1, 1, a.shape[-2], a.shape[-1]), gx, padding=ksize // 2)
    mu_a = F.conv2d(mu_a, gy, padding=ksize // 2)
    mu_b = F.conv2d(b.view(-1, 1, b.shape[-2], b.shape[-1]), gx, padding=ksize // 2)
    mu_b = F.conv2d(mu_b, gy, padding=ksize // 2)
    mu_a_sq, mu_b_sq, mu_ab = mu_a ** 2, mu_b ** 2, mu_a * mu_b
    var_a = F.conv2d(a.view(-1, 1, a.shape[-2], a.shape[-1]) ** 2, gx, padding=ksize // 2)
    var_a = F.conv2d(var_a, gy, padding=ksize // 2) - mu_a_sq
    var_b = F.conv2d(b.view(-1, 1, b.shape[-2], b.shape[-1]) ** 2, gx, padding=ksize // 2)
    var_b = F.conv2d(var_b, gy, padding=ksize // 2) - mu_b_sq
    cov = F.conv2d((a.view(-1, 1, a.shape[-2], a.shape[-1]) * b.view(-1, 1, b.shape[-2], b.shape[-1])),
                   gx, padding=ksize // 2)
    cov = F.conv2d(cov, gy, padding=ksize // 2) - mu_ab
    C1, C2 = 0.01 ** 2, 0.03 ** 2
    ssim_map = ((2 * mu_ab + C1) * (2 * cov + C2)) / ((mu_a_sq + mu_b_sq + C1) * (var_a + var_b + C2))
    return ssim_map.mean().item()


@torch.no_grad()
def evaluate(model, loader, device, noise_std):
    """Returns metrics for (a) clean reconstruction from clean input and
    (b) denoising (noisy input -> clean target)."""
    model.eval()
    totals = {key: [0.0, 0.0] for key in ("mse", "psnr", "ssim")}
    n = 0
    for x, _ in loader:
        x = x.to(device)
        noisy = (x + torch.randn_like(x) * noise_std).clamp(0, 1)
        recon_clean, _, _ = model(x)
        recon_denoise, _, _ = model(noisy)
        recon_clean = recon_clean.detach().clamp(0, 1)
        recon_denoise = recon_denoise.detach().clamp(0, 1)
        b = x.shape[0]
        n += b
        # clean reconstruction (input == target == x)
        totals["mse"][0] += torch.mean((recon_clean - x) ** 2).item() * b
        totals["psnr"][0] += psnr(recon_clean, x) * b
        totals["ssim"][0] += ssim(recon_clean, x) * b
        # denoising (input == noisy, target == x)
        totals["mse"][1] += torch.mean((recon_denoise - x) ** 2).item() * b
        totals["psnr"][1] += psnr(recon_denoise, x) * b
        totals["ssim"][1] += ssim(recon_denoise, x) * b
    out = {}
    for key, (c, d) in totals.items():
        out[(key, "clean")] = c / n
        out[(key, "denoise")] = d / n
    return out


