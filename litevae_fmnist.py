@torch.no_grad()
def plot_samples(model, loader, device, noise_std, out_path, n=8):
    model.eval()
    x, _ = next(iter(loader))
    x = x[:n].to(device)
    noisy = (x + torch.randn_like(x) * noise_std).clamp(0, 1)
    recon, _, _ = model(noisy)
    recon = recon.detach().clamp(0, 1)
    fig, axes = plt.subplots(3, n, figsize=(2 * n, 6))
    titles = ["Original", "Noisy", "Reconstructed"]
    for r, row in enumerate(axes):
        imgs = [x, noisy, recon][r]
        for i, ax in enumerate(row):
            ax.imshow(imgs[i].cpu().squeeze(0), cmap="gray")
            ax.axis("off")
            if i == 0:
                ax.set_ylabel(titles[r], fontsize=11)
    plt.suptitle("LiteVAE: Fashion-MNIST denoising samples", fontsize=13)
    plt.tight_layout()
    plt.savefig(out_path, dpi=120)
    plt.close(fig)


def plot_curves(history, out_path):
    fig, ax1 = plt.subplots(figsize=(6, 4))
    ax1.plot(history["recon"], label="Recon loss", color="tab:blue")
    ax1.set_xlabel("Epoch")
    ax1.set_ylabel("Reconstruction loss", color="tab:blue")
    ax1.tick_params(axis="y", labelcolor="tab:blue")
    ax2 = ax1.twinx()
    ax2.plot(history["kl"], label="KL loss", color="tab:red")
    ax2.set_ylabel("KL divergence", color="tab:red")
    ax2.tick_params(axis="y", labelcolor="tab:red")
    plt.title("LiteVAE training curves (Fashion-MNIST)")
    fig.tight_layout()
    fig.savefig(out_path, dpi=120)
    plt.close(fig)


