def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--epochs", type=int, default=15)
    ap.add_argument("--batch-size", type=int, default=128)
    ap.add_argument("--lr", type=float, default=1e-3)
    ap.add_argument("--latent-dim", type=int, default=16)
    ap.add_argument("--kl-weight", type=float, default=1e-4,
                    help="beta scaling of KL term (small so reconstruction dominates, "
                         "as in SD-VAE / LiteVAE training)")
    ap.add_argument("--noise-std", type=float, default=0.2)
    ap.add_argument("--data", type=str, default="./data")
    ap.add_argument("--out", type=str, default="./output/litevae_fmnist.png")
    ap.add_argument("--limit", type=int, default=-1, help="subsample trainset for quick runs")
    args = ap.parse_args()

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"Device: {device}")

    tf = transforms.Compose([transforms.ToTensor()])  # values in [0,1]
    train_ds = datasets.FashionMNIST(root=args.data, train=True, download=True, transform=tf)
    test_ds = datasets.FashionMNIST(root=args.data, train=False, download=True, transform=tf)
    if args.limit > 0:
        rng = torch.Generator().manual_seed(0)
        idx = torch.randperm(len(train_ds), generator=rng)[:args.limit]
        train_ds = torch.utils.data.Subset(train_ds, idx)
    train_loader = DataLoader(train_ds, batch_size=args.batch_size, shuffle=True,
                              num_workers=0)
    test_loader = DataLoader(test_ds, batch_size=args.batch_size, shuffle=False)

    model = LiteVAE(latent_dim=args.latent_dim).to(device)
    opt = torch.optim.AdamW(model.parameters(), lr=args.lr)
    history = {"recon": [], "kl": []}

    for ep in range(1, args.epochs + 1):
        model.train()
        r_loss = k_loss = 0.0
        n = 0
        for x, _ in train_loader:
            x = x.to(device)
            noisy = (x + torch.randn_like(x) * args.noise_std).clamp(0, 1)
            recon, mu, logvar = model(noisy)
            recon_loss, kl = vae_loss(recon, x, mu, logvar)
            loss = recon_loss + args.kl_weight * kl
            opt.zero_grad()
            loss.backward()
            opt.step()
            r_loss += recon_loss.item() * x.shape[0]
            k_loss += kl.item() * x.shape[0]
            n += x.shape[0]
        history["recon"].append(r_loss / n)
        history["kl"].append(k_loss / n)
        ev = evaluate(model, test_loader, device, args.noise_std)
        print(f"Epoch {ep:2d}/{args.epochs} | recon={history['recon'][-1]:.5f} "
              f"kl={history['kl'][-1]:.2f} | clean MSE={ev[('mse','clean')]:.5f} "
              f"PSNR={ev[('psnr','clean')]:.2f} SSIM={ev[('ssim','clean')]:.4f} | "
              f"denoise PSNR={ev[('psnr','denoise')]:.2f}")

    # final metrics
    ev = evaluate(model, test_loader, device, args.noise_std)
    print(f"\n=== FINAL TEST (noise std={args.noise_std}) ===")
    print(f"Clean reconstruction : MSE={ev[('mse','clean')]:.5f} "
          f"PSNR={ev[('psnr','clean')]:.2f} dB  SSIM={ev[('ssim','clean')]:.4f}")
    print(f"Denoising (std={args.noise_std}): MSE={ev[('mse','denoise')]:.5f} "
          f"PSNR={ev[('psnr','denoise')]:.2f} dB  SSIM={ev[('ssim','denoise')]:.4f}")

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    base = os.path.splitext(args.out)[0]
    plot_samples(model, test_loader, device, args.noise_std, args.out)
    plot_curves(history, base + "_curves.png")
    torch.save(model.state_dict(), base + "_weights.pt")
    print("Saved figures & weights to", os.path.dirname(args.out))


if __name__ == "__main__":
    main()