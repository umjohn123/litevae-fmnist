"""
LiteVAE-style implementation for Fashion-MNIST reconstruction & denoising.

This code is GENERATED BY AN AI ASSISTANT for AI Assignment #1 (CISC3024
Pattern Recognition). It implements the core idea of LiteVAE
(Sadat et al., NeurIPS 2024): a variational autoencoder whose encoder is
front-loaded with a 2D Haar Discrete Wavelet Transform (DWT), plus a
lightweight feature-extraction / aggregation network and a fully
convolutional decoder.

Adaptation note:
  - The original LiteVAE uses 3 DWT levels (8x downsampling) on large images.
    Fashion-MNIST is 28x28, which supports exactly 2 DWT levels
    (28 -> 14 -> 7). We therefore use num_levels=2 (4x downsampling, latent
    grid 7x7) to stay integer-sized.
  - Only the light variant is used so the model trains fast on CPU.
"""

import os
